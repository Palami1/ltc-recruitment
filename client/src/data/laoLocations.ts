export const PROVINCE_NAMES = LAO_LOCATIONS.map(p => p.name);

export function getDistrictsByProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const normalized = provinceName.trim();
  const prov = LAO_LOCATIONS.find(
    p => p.name === normalized || p.name.includes(normalized) || normalized.includes(p.name)
  );
  return prov ? prov.districts : [];
}
